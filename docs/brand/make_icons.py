#!/usr/bin/env python3
"""Ironterm icon: a barbell drawn in contribution-graph squares (blue ramp), with the amber
"today" square in the middle of the bar. One source for every platform:

  python3 docs/brand/make_icons.py          # writes all of the files below
  python3 docs/brand/make_icons.py --grid   # same barbell on a faint contribution-graph grid

  docs/brand/icon.svg                                         README / web
  web/public/favicon.svg                                      browser tab
  android/app/src/main/res/drawable/ic_launcher_foreground.xml  adaptive icon (fits the safe zone)
  android/app/src/main/res/drawable/ic_launcher_monochrome.xml  Android 13+ themed icon
  ios/Ironterm/Assets.xcassets/AppIcon.appiconset/icon-1024.png  (needs Pillow)
"""
import os, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
GRID = "--grid" in sys.argv  # faint backing grid behind the barbell
AMBER = "#ffb000"
RAMP = ["#16181d", "#0f3278", "#285ab4", "#5082dc", "#8cb4ff"]  # level 0..4, same as the graph
_ = 0
# Side view, heaviest plates innermost. From the centre out: bar (amber = today), collar,
# big plate, small plate, sleeve.
CELLS = [
    [_, _, 4, _, _, _, _, _, _, _, 4, _, _],
    [_, 3, 4, _, _, _, _, _, _, _, 4, 3, _],
    [_, 3, 4, 3, _, _, _, _, _, 3, 4, 3, _],
    [2, 3, 4, 3, 2, 2, -1, 2, 2, 3, 4, 3, 2],
    [_, 3, 4, 3, _, _, _, _, _, 3, 4, 3, _],
    [_, 3, 4, _, _, _, _, _, _, _, 4, 3, _],
    [_, _, 4, _, _, _, _, _, _, _, 4, _, _],
]
COLS, ROWS = len(CELLS[0]), len(CELLS)
GAP = 1.6 / 7.6  # gap as a fraction of a square


def cells(width, cx, cy):
    """(x, y, size, level) for every square, the grid `width` wide, centred on (cx, cy)."""
    s = width / (COLS + (COLS - 1) * GAP)
    g = s * GAP
    h = ROWS * s + (ROWS - 1) * g
    x0, y0 = cx - width / 2, cy - h / 2
    for r, row in enumerate(CELLS):
        for c, v in enumerate(row):
            if v == 0 and not GRID:
                continue
            yield x0 + c * (s + g), y0 + r * (s + g), s, v


def color(v):
    return AMBER if v == -1 else RAMP[v]


def svg(size=108, radius=24, width=100):
    rects = "".join(
        f'<rect x="{x:.2f}" y="{y:.2f}" width="{s:.2f}" height="{s:.2f}" rx="{s * .18:.2f}" fill="{color(v)}"/>'
        for x, y, s, v in cells(width, size / 2, size / 2))
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {size} {size}">'
            f'<rect width="{size}" height="{size}" rx="{radius}" fill="#000"/>{rects}</svg>\n')


def rrect(x, y, s, r):
    k = s - 2 * r
    return (f"M{x + r:.2f},{y:.2f}h{k:.2f}a{r:.2f},{r:.2f} 0 0 1 {r:.2f},{r:.2f}v{k:.2f}"
            f"a{r:.2f},{r:.2f} 0 0 1 -{r:.2f},{r:.2f}h-{k:.2f}a{r:.2f},{r:.2f} 0 0 1 -{r:.2f},-{r:.2f}"
            f"v-{k:.2f}a{r:.2f},{r:.2f} 0 0 1 {r:.2f},-{r:.2f}z")


def vector(mono=False):
    # Adaptive icons are 108dp; launchers may mask to a 66dp circle, so the barbell's outer
    # sleeves (middle row) must stay within ±33dp of the centre: barbell 64dp wide.
    paths = {}
    for x, y, s, v in cells(64, 54, 54):
        if mono and v == 0:
            continue
        key = ("#FFFFFFFF" if v == -1 else ["#33FFFFFF", "#66FFFFFF", "#99FFFFFF", "#CCFFFFFF", "#FFFFFFFF"][v]) if mono else color(v)
        paths.setdefault(key, []).append(rrect(x, y, s, s * .18))
    body = "\n".join(f'    <path android:fillColor="{k}" android:pathData="{" ".join(d)}" />' for k, d in paths.items())
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            "<!-- GENERATED by docs/brand/make_icons.py -->\n"
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="108dp" android:height="108dp"\n'
            '    android:viewportWidth="108" android:viewportHeight="108">\n'
            f"{body}\n</vector>\n")


def png(path, size=1024):
    from PIL import Image, ImageDraw
    k = 4  # supersample, then downscale for smooth corners
    img = Image.new("RGB", (size * k, size * k), (0, 0, 0))
    d = ImageDraw.Draw(img)
    for x, y, s, v in cells(size * k * 0.80, size * k / 2, size * k / 2):  # iOS masks the corners itself
        d.rounded_rectangle([x, y, x + s, y + s], radius=s * .18, fill=color(v))
    img.resize((size, size), Image.LANCZOS).save(path)


def write(rel, text):
    p = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w") as f:
        f.write(text)
    print("wrote", rel)


if __name__ == "__main__":
    write("docs/brand/icon.svg", svg())
    write("web/public/favicon.svg", svg())
    write("android/app/src/main/res/drawable/ic_launcher_foreground.xml", vector())
    write("android/app/src/main/res/drawable/ic_launcher_monochrome.xml", vector(mono=True))
    out = "ios/Ironterm/Assets.xcassets/AppIcon.appiconset/icon-1024.png"
    png(os.path.join(ROOT, out))
    print("wrote", out)
