object Live {
    /** Session JSON: same shape the web app writes; nulls are sent explicitly like JSON.stringify of TS nulls. */
    val json = Json {
        ignoreUnknownKeys = true
        coerceInputValues = true
        encodeDefaults = true
        explicitNulls = false
    }

    fun encode(s: LiveSession): String = json.encodeToString(LiveSession.serializer(), s)
    fun decode(text: String): LiveSession = json.decodeFromString(LiveSession.serializer(), text)

    private val ISO = DateTimeFormatter.ofPattern("yyyy-MM-dd'T'HH:mm:ss.SSS'Z'").withZone(ZoneOffset.UTC)

    /** JS Date.toISOString(): always UTC with milliseconds. */
    fun iso(epochMs: Long): String = ISO.format(Instant.ofEpochMilli(epochMs))

    /** Date.parse for the ISO strings the app and the server write (Z or offset). */
    fun parseMs(iso: String?): Long? {
        if (iso.isNullOrBlank()) return null
        return runCatching { Instant.parse(iso).toEpochMilli() }.getOrNull()
            ?: runCatching { OffsetDateTime.parse(iso).toInstant().toEpochMilli() }.getOrNull()
    }

    var random: Random = Random.Default

    /** Math.random().toString(36).slice(2, 10) */
    fun uid(): String {
        val chars = "0123456789abcdefghijklmnopqrstuvwxyz"
        return String(CharArray(8) { chars[random.nextInt(chars.length)] })
    }

    /** units.ts roundTo: Math.round(w / step) * step (JS rounds .5 up). */
    fun roundTo(w: Double, step: Double): Double = jsRound(w / step) * step

    fun jsRound(x: Double): Double = floor(x + 0.5)

    /** units.ts loadStep (no microplates). */
    fun loadStep(kind: String, unit: String): Double = when (kind) {
        "dumbbell" -> if (unit == "lb") 5.0 else 2.0
        "machine" -> 2.5
        else -> if (unit == "lb") 5.0 else 2.5
    }

    fun bar(unit: String): Double = if (unit == "lb") 45.0 else 20.0

    /** units.ts plates: plates per side for a barbell load. */
    fun plates(total: Double, unit: String, bar: Double = bar(unit)): List<Double> {
        val avail = if (unit == "lb") listOf(45.0, 35.0, 25.0, 10.0, 5.0, 2.5) else listOf(25.0, 20.0, 15.0, 10.0, 5.0, 2.5, 1.25)
        var side = (total - bar) / 2
        val out = ArrayList<Double>()
        if (side <= 0) return out
        for (p in avail) {
            while (side >= p - 1e-6) {
                out.add(p)
                side -= p
            }
        }
        return out
    }

    /** Warmup ramp for a heavy barbell top set: bar, then ~40/60/80%. */
    fun warmups(top: Double, unit: String): List<LiveSet> {
        val bar = bar(unit)
        if (top <= bar * 1.5) return emptyList()
        val step = if (unit == "lb") 5.0 else 2.5
        val out = arrayListOf(LiveSet(type = SetType.WARMUP, weight = bar, reps = 10, done = false))
        for ((f, r) in listOf(0.4 to 5, 0.6 to 3, 0.8 to 2)) {
            val w = roundTo(top * f, step)
            if (w > bar && w < top) out.add(LiveSet(type = SetType.WARMUP, weight = w, reps = r, done = false))
        }
        return out
    }

    /** Start a session from the program's planned day (offline fallback; normally the server does this). */
    fun sessionFromPlan(plan: PlannedSession, unit: String, programName: String, now: String = iso(System.currentTimeMillis())): LiveSession {
        val exercises = plan.exercises.map { ex ->
            val lift = LiftLibrary[ex.lift]
            val top = max(0.0, ex.sets.maxOfOrNull { it.weight } ?: 0.0)
            val heavy = (ex.tier == "T1" || ex.tier == "MAIN") && (lift?.kind ?: "barbell") == "barbell"
            val work = ex.sets.map { s ->
                LiveSet(
                    type = if (s.amrap) SetType.FAILURE else SetType.NORMAL,
                    weight = s.weight.takeIf { it != 0.0 },
                    reps = s.reps,
                    rpe = null,
                    done = false,
                    target = LiveTarget(s.weight, s.reps, s.repsMax, s.amrap, s.rpe, if (s.ofTop == true) s.pct?.takeIf { it != 0.0 } else null),
                )
            }
            LiveExercise(
                id = uid(), lift = ex.lift, slotId = ex.slotId, tier = ex.tier, scheme = ex.scheme, note = ex.note,
                ifSuccess = ex.ifSuccess, ifFail = ex.ifFail, restSeconds = ex.restSeconds,
                totalReps = ex.totalReps?.takeIf { it != 0 },
                totalRepsMax = if (truthy(ex.totalReps)) ex.totalRepsMax?.takeIf { it != 0 } else null,
                sets = (if (heavy && top != 0.0) warmups(top, unit) else emptyList()) + work,
            )
        }
        return LiveSession(
            id = uid(), startedAt = now, unit = unit, programName = programName, dayId = plan.dayId, dayName = plan.dayName,
            title = "${programName.split(" ")[0]} · ${plan.dayId}", exercises = exercises, restEndsAt = null,
        )
    }

    fun emptySession(unit: String, now: String = iso(System.currentTimeMillis()), zone: ZoneId = ZoneId.systemDefault()): LiveSession {
        val h = Instant.ofEpochMilli(parseMs(now) ?: System.currentTimeMillis()).atZone(zone).hour
        val part = if (h < 11) "Morning" else if (h < 17) "Afternoon" else "Evening"
        return LiveSession(id = uid(), startedAt = now, unit = unit, title = "$part workout", exercises = emptyList(), restEndsAt = null)
    }

    fun addExercise(s: LiveSession, lift: String, cardio: Boolean = false, title: String? = null, templateId: String? = null): LiveSession {
        val ex = LiveExercise(
            id = uid(), lift = lift, title = title, templateId = templateId, restSeconds = if (cardio) 0 else 90, cardio = if (cardio) true else null,
            sets = listOf(
                if (cardio) LiveSet(type = SetType.NORMAL, weight = null, reps = null, durationSec = 1800.0, distanceM = null, done = false)
                else LiveSet(type = SetType.NORMAL, weight = null, reps = 8, done = false),
            ),
        )
        return s.copy(exercises = s.exercises + ex)
    }

    /** Copy the last set (weight/reps) as a new undone set. */
    fun addSet(s: LiveSession, exId: String): LiveSession = mapEx(s, exId) { ex ->
        val last = ex.sets.lastOrNull()
        val next = last?.copy(type = if (last.type == SetType.WARMUP) SetType.NORMAL else last.type, done = false, doneAt = null, target = null, skipped = null)
            ?: LiveSet(type = SetType.NORMAL, weight = null, reps = 5, done = false)
        ex.copy(sets = ex.sets + next)
    }

    fun mapEx(s: LiveSession, exId: String, f: (LiveExercise) -> LiveExercise): LiveSession =
        s.copy(exercises = s.exercises.map { if (it.id == exId) f(it) else it })

    /** Reps you change are yours: the app stops pacing that set (auto is cleared unless the patch sets it). */
    fun updateSet(s: LiveSession, exId: String, i: Int, patch: (LiveSet) -> LiveSet): LiveSession =
        mapEx(s, exId) { ex ->
            ex.copy(sets = ex.sets.mapIndexed { k, x ->
                if (k != i) x else patch(x).let { y -> if (y.reps != x.reps && y.auto == x.auto) y.copy(auto = null) else y }
            })
        }

    /** Reps typed by you (keypad / stepper): like TS updateSet(…, {reps}), the set stops following the pace. */
    fun setReps(s: LiveSession, exId: String, i: Int, reps: Int?): LiveSession = updateSet(s, exId, i) { it.copy(reps = reps, auto = null) }

    /** Working reps done so far (warm-ups and skipped sets don't count). */
    fun repsDone(ex: LiveExercise): Int = ex.sets.sumOf { x -> if (x.done && !x.isSkipped && x.type != SetType.WARMUP) x.reps ?: 0 else 0 }

    /** Skip a set (or bring it back): skipped sets aren't done, saved or counted. */
    fun skipSet(s: LiveSession, exId: String, i: Int, skipped: Boolean = true): LiveSession =
        updateSet(s, exId, i) { if (skipped) it.copy(skipped = true, done = false, doneAt = null) else it.copy(skipped = false) }

    /** Skip every set of an exercise that isn't done yet. */
    fun skipExercise(s: LiveSession, exId: String): LiveSession =
        mapEx(s, exId) { ex -> ex.copy(sets = ex.sets.map { x -> if (x.done) x else x.copy(skipped = true, doneAt = null) }) }

    /**
     * A rep-total exercise ("100 total reps") after set [i]: the sets still planned follow the reps you
     * actually do (sets of 5 instead of 20), one more set is added while you're short, and once the
     * total is reached any planned sets left over are skipped.
     */
    private fun chaseTotal(ex: LiveExercise, i: Int): LiveExercise {
        val total = ex.totalReps
        if (!truthy(total) || ex.isCardio) return ex
        val set = ex.sets.getOrNull(i) ?: return ex
        if (set.type == SetType.WARMUP || !set.done) return ex
        val left = total!! - repsDone(ex)
        val pace = set.reps?.takeIf { it > 0 }
        var sets = ex.sets.mapIndexed { k, x ->
            when {
                k <= i || x.done || x.isSkipped || x.type == SetType.WARMUP -> x
                left <= 0 -> x.copy(skipped = true)
                else -> {
                    // a planned set you haven't touched takes your pace (and never more than what's left)
                    val untouched = x.auto == true || (x.target != null && x.reps == x.target.reps)
                    if (untouched && pace != null) x.copy(reps = min(pace, left), auto = true) else x
                }
            }
        }
        val planned = sets.filter { !it.done && !it.isSkipped && it.type != SetType.WARMUP }.sumOf { it.reps ?: 0 }
        if (left > 0 && planned < left) {
            val reps = min(pace ?: set.target?.reps?.takeIf { it != 0 } ?: 10, left - planned)
            if (reps > 0) sets = sets + LiveSet(
                type = SetType.NORMAL, weight = set.weight, reps = reps, rpe = null, done = false, auto = true,
                target = set.target?.copy(reps = reps, repsMax = null, amrap = false),
            )
        }
        return ex.copy(sets = sets)
    }

    private fun truthy(x: Double?) = x != null && x != 0.0 && !x.isNaN()
    private fun truthy(x: Int?) = x != null && x != 0

    /** Mark a set done and start the rest timer. Back-off sets keyed to today's top set get their load filled in. */
    fun completeSet(s: LiveSession, exId: String, i: Int, nowMs: Long = System.currentTimeMillis()): LiveSession {
        var next = updateSet(s, exId, i) { it.copy(done = true, doneAt = iso(nowMs), skipped = null) }
        next = mapEx(next, exId) { e -> chaseTotal(e, i) }
        val ex = next.exercises.first { it.id == exId }
        val set = ex.sets[i]
        // A finished top set sets the load for "% of top" back-offs.
        if (truthy(set.weight) && truthy(set.reps) && ex.sets.any { truthy(it.target?.ofTop) && !it.done && !truthy(it.weight) }) {
            val w = set.weight!!
            val r = set.reps!!
            val e1 = if (r <= 1) w else w * (1 + r / 30.0)
            val step = loadStep(LiftLibrary[ex.lift]?.kind ?: "barbell", s.unit)
            next = mapEx(next, exId) { e ->
                e.copy(sets = e.sets.map { x ->
                    if (truthy(x.target?.ofTop) && !x.done && !truthy(x.weight)) x.copy(weight = roundTo(e1 * x.target!!.ofTop!!, step)) else x
                })
            }
        }
        val rest = if (set.type == SetType.WARMUP) min(60, ex.restSeconds) else ex.restSeconds
        val more = next.exercises.first { it.id == exId }.sets.any { it.isOpen }
        return next.copy(
            restEndsAt = if (rest != 0 && (more || hasNextExercise(next, exId))) iso(nowMs + rest * 1000L) else null,
            restFor = exId,
        )
    }

    private fun hasNextExercise(s: LiveSession, exId: String): Boolean {
        val i = s.exercises.indexOfFirst { it.id == exId }
        return s.exercises.drop(i + 1).any { e -> e.sets.any { it.isOpen } }
    }

    /** The exercise and set to do next. */
    fun current(s: LiveSession): Cursor? {
        for (e in s.exercises) {
            val k = e.sets.indexOfFirst { it.isOpen }
            if (k >= 0) return Cursor(e.id, k)
        }
        return null
    }

    fun progress(s: LiveSession): Progress {
        val all = s.exercises.flatMap { e -> e.sets.filter { it.type != SetType.WARMUP && !it.isSkipped } }
        return Progress(all.count { it.done }, all.size)
    }

    // ── exercise header / rep-total line (web/src/views/gym.tsx ExerciseCard) ──

    /** Done: the rep total is reached, or every set that isn't skipped is done. */
    fun isComplete(ex: LiveExercise): Boolean {
        val total = ex.totalReps
        if (total != null && total > 0) return repsDone(ex) >= total
        val counted = ex.sets.filter { !it.isSkipped }
        return counted.isNotEmpty() && counted.all { it.done }
    }

    /** Nothing left to do but it isn't complete: the rest was skipped. */
    fun isSkippedOut(ex: LiveExercise): Boolean = !isComplete(ex) && ex.sets.none { it.isOpen }

    /** "65/100 reps", "65/100–200 reps" or "3/5" (sets done / sets not skipped), plus " · skipped" when the rest was skipped. */
    fun countLabel(ex: LiveExercise): String {
        val total = ex.totalReps?.takeIf { it > 0 }
        val base = if (total != null) "${repsDone(ex)}/$total${ex.totalRepsMax?.takeIf { it > 0 }?.let { "–$it" } ?: ""} reps"
        else ex.sets.filter { !it.isSkipped }.let { c -> "${c.count { it.done }}/${c.size}" }
        return if (isSkippedOut(ex)) "$base · skipped" else base
    }

    /** The rep-total line in the open exercise, null for a set-by-set exercise. */
    fun totalLine(ex: LiveExercise): String? {
        val total = ex.totalReps?.takeIf { it > 0 } ?: return null
        val reps = repsDone(ex)
        return when {
            reps >= total -> "$reps reps: total reached"
            isSkippedOut(ex) -> "skipped at $reps of $total reps · + SET to keep going"
            else -> "${total - reps} reps to go · sets are added as you go"
        }
    }

    // ── UI operations from web/src/views/gym.tsx (kept here so they are unit tested too) ──

    fun undoSet(s: LiveSession, exId: String, i: Int) = updateSet(s, exId, i) { it.copy(done = false, doneAt = null) }

    fun removeSet(s: LiveSession, exId: String, i: Int) = mapEx(s, exId) { e -> e.copy(sets = e.sets.filterIndexed { k, _ -> k != i }) }

    fun removeExercise(s: LiveSession, exId: String) = s.copy(exercises = s.exercises.filter { it.id != exId })

    fun setUserNote(s: LiveSession, exId: String, note: String) = mapEx(s, exId) { it.copy(userNote = note) }

    /** −15 s: restEndsAt − 15 s. */
    fun restMinus(s: LiveSession, sec: Int = 15): LiveSession {
        val end = parseMs(s.restEndsAt) ?: return s
        return s.copy(restEndsAt = iso(end - sec * 1000L))
    }

    /** +30 s: max(now, restEndsAt) + 30 s. */
    fun restPlus(s: LiveSession, nowMs: Long = System.currentTimeMillis(), sec: Int = 30): LiveSession {
        val end = parseMs(s.restEndsAt) ?: return s
        return s.copy(restEndsAt = iso(max(nowMs, end) + sec * 1000L))
    }

    fun skipRest(s: LiveSession) = s.copy(restEndsAt = null)

    /** Seconds of rest left (negative once it's over), null when no timer. */
    fun restLeft(s: LiveSession, nowMs: Long): Double? = parseMs(s.restEndsAt)?.let { (it - nowMs) / 1000.0 }

    /** Working-set number shown on the card (warmups are "W"). */
    fun setLabel(ex: LiveExercise, i: Int): String =
        if (ex.sets[i].type == SetType.WARMUP) "W" else ex.sets.take(i + 1).count { it.type != SetType.WARMUP }.toString()

    /** Set [i] as "n of N" among the working sets you'll actually do (warm-ups and skipped sets left out); null for a warm-up or skipped set. */
    fun workingPosition(ex: LiveExercise, i: Int): Pair<Int, Int>? {
        val x = ex.sets.getOrNull(i) ?: return null
        if (x.type == SetType.WARMUP || x.isSkipped) return null
        val counted = { y: LiveSet -> y.type != SetType.WARMUP && !y.isSkipped }
        return ex.sets.take(i + 1).count(counted) to ex.sets.count(counted)
    }

    /** e1RM (Epley) of a done set, the same formula the server uses. */
    fun e1rm(weight: Double, reps: Int): Double = if (reps <= 1) weight else weight * (1 + reps / 30.0)

    /** Completed sets / volume (weight × reps, session unit) / duration so far. */
    data class Summary(val sets: Int, val volume: Double, val durationSec: Long, val exercises: Int)

    fun summary(s: LiveSession, endMs: Long): Summary {
        val done = s.exercises.flatMap { e -> e.sets.filter { it.done }.map { e to it } }
        val vol = done.filter { (e, x) -> !e.isCardio && x.type != SetType.WARMUP }.sumOf { (_, x) -> (x.weight ?: 0.0) * (x.reps ?: 0) }
        val start = parseMs(s.startedAt) ?: endMs
        return Summary(done.count { it.second.type != SetType.WARMUP }, vol, max(0L, (endMs - start) / 1000), s.exercises.count { e -> e.sets.any { it.done } })
    }

    // ── Hevy body (Direct mode posts it straight to POST /v1/workouts) ──

    const val LB_PER_KG = 2.20462262185

    fun toKg(w: Double, unit: String) = if (unit == "kg") w else w / LB_PER_KG

    /** notes.ts exerciseNote */
    fun exerciseNote(user: String?, tier: String?, scheme: String?): String? =
        listOfNotNull(user?.trim()?.takeIf { it.isNotEmpty() }, if (!scheme.isNullOrEmpty()) "${tier ?: ""} $scheme".trim().takeIf { it.isNotEmpty() } else null)
            .joinToString(" · ").ifEmpty { null }

    fun toHevyWorkout(s: LiveSession, templateFor: (LiveExercise) -> String, end: String = iso(System.currentTimeMillis())): HevyWorkoutBody {
        fun kg(w: Double?) = w?.let { jsRound(toKg(it, s.unit) * 100) / 100 }
        val exercises = s.exercises
            .map { it to it.sets.filter { x -> x.done } }
            .filter { it.second.isNotEmpty() }
            .map { (ex, sets) ->
                HevyWorkoutBody.Exercise(
                    exercise_template_id = templateFor(ex),
                    superset_id = null,
                    notes = exerciseNote(ex.userNote, ex.tier, ex.scheme),
                    sets = sets.map { x ->
                        HevyWorkoutBody.Set(
                            type = x.type,
                            weight_kg = if (ex.isCardio) null else kg(x.weight),
                            reps = if (ex.isCardio) null else x.reps,
                            distance_meters = x.distanceM,
                            duration_seconds = x.durationSec,
                            rpe = x.rpe,
                            custom_metric = null,
                        )
                    },
                )
            }
        return HevyWorkoutBody(
            HevyWorkoutBody.Workout(
                title = s.title,
                description = listOfNotNull(s.notes?.takeIf { it.isNotEmpty() }, s.dayId?.takeIf { it.isNotEmpty() }?.let { "[ht:$it]" }).joinToString("\n"),
                start_time = s.startedAt,
                end_time = end,
                is_private = false,
                exercises = exercises,
            ),
        )
    }
}

