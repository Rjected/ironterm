/** Reads 8, 8.0 or "8" (the web app parses typed input with Number()); writes an int. */
object LenientInt : KSerializer<Int> {
    override val descriptor = PrimitiveSerialDescriptor("LenientInt", PrimitiveKind.INT)
    override fun serialize(encoder: Encoder, value: Int) = encoder.encodeInt(value)
    override fun deserialize(decoder: Decoder): Int {
        if (decoder is JsonDecoder) {
            val el = decoder.decodeJsonElement()
            return ((el as? JsonPrimitive)?.let { it.doubleOrNull ?: it.content.toDoubleOrNull() } ?: 0.0).let { Live.jsRound(it).toInt() }
        }
        return decoder.decodeInt()
    }
}

object LenientIntN : KSerializer<Int?> {
    override val descriptor = PrimitiveSerialDescriptor("LenientIntN", PrimitiveKind.INT)
    @OptIn(kotlinx.serialization.ExperimentalSerializationApi::class)
    override fun serialize(encoder: Encoder, value: Int?) = if (value == null) encoder.encodeNull() else encoder.encodeInt(value)
    override fun deserialize(decoder: Decoder): Int? {
        if (decoder is JsonDecoder) {
            val el = decoder.decodeJsonElement()
            val p = el as? JsonPrimitive ?: return null
            if (p is kotlinx.serialization.json.JsonNull) return null
            return (p.doubleOrNull ?: p.content.toDoubleOrNull())?.let { Live.jsRound(it).toInt() }
        }
        return decoder.decodeInt()
    }
}
