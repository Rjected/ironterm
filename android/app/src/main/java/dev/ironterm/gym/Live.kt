// Kotlin port of web/shared/live.ts: the in-progress gym session, logged set by set, written to
// Hevy when you finish. The JSON shape is the server's (PUT /api/live, POST /api/live/finish), so
// a session can move between the web app and this app. Every function is pure and mirrors its TS
// namesake; LiveTest replays golden cases generated by the TS code (test resources/live_golden.json).

/** warmup | normal | failure | dropset (Hevy set types). */
object SetType {
    const val WARMUP = "warmup"
    const val NORMAL = "normal"
    const val FAILURE = "failure"
    const val DROPSET = "dropset"
    val all = listOf(WARMUP, NORMAL, FAILURE, DROPSET)
}

@Serializable
data class LiveTarget(
    val weight: Double = 0.0,
    @Serializable(LenientInt::class) val reps: Int = 0,
    @Serializable(LenientIntN::class) val repsMax: Int? = null,
    val amrap: Boolean = false,
    val rpe: Double? = null,
    /** % of today's top set (back-offs) */
    val ofTop: Double? = null,
)

@Serializable
data class LiveSet(
    val type: String = SetType.NORMAL,
    /** in the session's unit; null = bodyweight / not entered */
    val weight: Double? = null,
    @Serializable(LenientIntN::class) val reps: Int? = null,
    val rpe: Double? = null,
    val durationSec: Double? = null,
    val distanceM: Double? = null,
    val done: Boolean = false,
    val doneAt: String? = null,
    val target: LiveTarget? = null,
    /** skipped on purpose: not done, not saved, not counted (null = false; old sessions don't have it) */
    val skipped: Boolean? = null,
    /** reps were set by the app (a rep-total exercise following your pace), not by you */
    val auto: Boolean? = null,
) {
    val isWarmup: Boolean get() = type == SetType.WARMUP
    val isSkipped: Boolean get() = skipped == true
    /** still to do: not done and not skipped */
    val isOpen: Boolean get() = !done && skipped != true
}

@Serializable
data class LiveExercise(
    val id: String,
    val lift: String,
    /** Hevy title for exercises outside the lift library */
    val title: String? = null,
    val templateId: String? = null,
    val slotId: String? = null,
    val tier: String? = null,
    val scheme: String? = null,
    /** program note, e.g. "Retest 5RM" */
    val note: String? = null,
    /** your own note for this exercise; saved to Hevy as the exercise note */
    val userNote: String? = null,
    val ifSuccess: String? = null,
    val ifFail: String? = null,
    @Serializable(LenientInt::class) val restSeconds: Int = 90,
    val cardio: Boolean? = null,
    /** reach this many working reps in as many sets as it takes ("100 total reps"); sets are added as you go */
    @Serializable(LenientIntN::class) val totalReps: Int? = null,
    @Serializable(LenientIntN::class) val totalRepsMax: Int? = null,
    val sets: List<LiveSet> = emptyList(),
) {
    val isCardio: Boolean get() = cardio == true
    val def: LiftDef? get() = LiftLibrary[lift]
    val kind: String get() = def?.kind ?: "barbell"
    val displayName: String get() = title ?: def?.name ?: lift
}

